package com.oracole.readit.data

/**
 * 页面切换的转场风格
 *
 * 放在设置里，是为了能在一台手机上、同一个应用里直接对比
 * 选定一个之后，其余的可以删掉
 */
enum class TransitionStyle(val label: String, val desc: String) {

    /** 不做转场，直接换页。留作对照，能看清有没有转场差多少 */
    NONE("无", "直接换页"),

    /** 只做透明度过渡，不带位移 */
    FADE("淡入淡出", "新旧页交叉淡过"),

    /** 新页整屏滑入，旧页整屏滑出 */
    SLIDE("整屏滑动", "新页从右侧推入"),

    /** 新页整屏滑入，旧页滑出并缩小、淡出 */
    SLIDE_SCALE("滑动 + 缩放", "旧页退后半步并缩小"),

    /** 新页整屏滑入，旧页只退三分之一，形成视差 */
    PARALLAX("视差滑动", "新页盖上来，旧页退一部分"),
}
